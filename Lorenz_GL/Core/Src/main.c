static void gl_compute_binomial_coefs(double alpha, int m)
{
    c_coef[0] = 1.0;
    for (int j = 1; j <= m; j++) {
        /* c[j] = c[j-1]*(1 - (1+alpha)/j) = (-1)^j * C(alpha,j) */
        const double tmp = (1.0 + alpha) / (double)j;
        c_coef[j] = c_coef[j - 1] * (1.0 - tmp);
    }
}

static void lorenz_gl_step(void)
{
    /* i = paso que vamos a escribir; el más reciente está en idx_current */
    const int N = m + 1;
    const int i = step_count + 1;

    /* cuántos términos pasados sumar */
    const int pasos = (i < m) ? i : m;

    /* índice del estado anterior (i-1) en el buffer circular */
    const int idx_prev = idx_current;

    /* acumular memoria: sum_{j=1..pasos} c[j] * x[i-j] */
    long double sum_x = 0.0L, sum_y = 0.0L, sum_z = 0.0L;
    int run_idx = idx_prev;
    for (int j = 1; j <= pasos; j++) {
        sum_x += (long double)c_coef[j] * (long double)x_hist[run_idx];
        sum_y += (long double)c_coef[j] * (long double)y_hist[run_idx];
        sum_z += (long double)c_coef[j] * (long double)z_hist[run_idx];
        if (--run_idx < 0) run_idx += N;
    }

    /* derivada local en (i-1) */
    const long double x_prev = x_hist[idx_prev];
    const long double y_prev = y_hist[idx_prev];
    const long double z_prev = z_hist[idx_prev];

    const long double dx = SIGMA * (y_prev - x_prev);
    const long double dy = RHO * x_prev - y_prev - x_prev * z_prev;
    const long double dz = -BETA * z_prev + x_prev * y_prev;

    /* actualización GL: x[i] = dt^alpha * f(x_{i-1}) - \sum_{j>=1} c[j] x[i-j] */
    const long double x_new = dx * (long double)dt_alpha - sum_x;
    const long double y_new = dy * (long double)dt_alpha - sum_y;
    const long double z_new = dz * (long double)dt_alpha - sum_z;

    /* escribir en buffer circular */
    idx_current = (idx_current + 1) % N;
    x_hist[idx_current] = (double)x_new;
    y_hist[idx_current] = (double)y_new;
    z_hist[idx_current] = (double)z_new;

    step_count++;
}

static uint32_t float_to_dac12(double val, double minVal, double maxVal)
{
    double rango = maxVal - minVal;
    if (fabs(rango) < 1e-12) rango = 1e-12;
    double s = (val - minVal) * (4095.0 / rango);
    if (s < 0.0) s = 0.0;
    if (s > 4095.0) s = 4095.0;
    return (uint32_t)lround(s);
}

static void enviar_mensaje(const char *msg)
{
    if (uart_busy) return;
    size_t n = strnlen(msg, sizeof(tx_buffer) - 1);
    memcpy(tx_buffer, msg, n);
    tx_buffer[n] = '\0';
    uart_busy = 1;
    if (HAL_UART_Transmit_IT(&huart3, (uint8_t*)tx_buffer, (uint16_t)n) != HAL_OK) {
        uart_busy = 0;
    }
}

void HAL_UART_TxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart == &huart3) uart_busy = 0;
}

