	  lorenz_gl_step();

	  const double x = x_hist[idx_current];
	  const double y = y_hist[idx_current];
	  const double z = z_hist[idx_current];

	  HAL_DAC_SetValue(&hdac, DAC_CHANNEL_1, DAC_ALIGN_12B_R, float_to_dac12(x, -20.0, 20.0));
	  HAL_DAC_SetValue(&hdac, DAC_CHANNEL_2, DAC_ALIGN_12B_R, float_to_dac12(y, -25.0, 25.0));

	  char buf[96];
	  /* decimales por UART para graficar en PC */
